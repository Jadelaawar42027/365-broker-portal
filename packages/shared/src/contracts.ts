/**
 * File: packages/shared/src/contracts.ts
 * Purpose: Contract signing on onboarding step 3 (SPEC D31): the two documents every broker signs, their statuses,
 * the exact e-sign consent and company authorization wording (stored with every signature), Eastern-time contract
 * dates, the field-map shape of a template, and the HTTP contract for the broker signing flow, the company signature
 * and the admin contract actions.
 *
 * Functions:
 * - contractDate(date): the date in America/New_York as MM/DD/YYYY, as printed on the documents.
 * - easternTimestamp(date): a readable Eastern date and time for the signature certificate.
 * - contractStatusLabel(status): the plain-language label for a document status.
 * - isPngDataUrl(value): true for a base64 PNG data URL.
 */
import { z } from "zod";
import { isoDateSchema } from "./schemas";

export const CONTRACT_STEP_KEY = "contract_nda";
export const CONTRACT_TEMPLATE_KEYS = ["broker_agreement", "mutual_nda"] as const;
export type ContractTemplateKey = (typeof CONTRACT_TEMPLATE_KEYS)[number];

export const CONTRACT_TITLES: Record<ContractTemplateKey, { title: string; short: string }> = {
  broker_agreement: { title: "Broker Independent Contractor & Commission Agreement", short: "Broker Agreement" },
  mutual_nda: { title: "Mutual Non-Disclosure & Non-Compete Agreement", short: "NDA" },
};

export const CONTRACT_STATUSES = ["pending", "broker_signed", "fully_signed", "signed_outside", "voided"] as const;
export type ContractStatus = (typeof CONTRACT_STATUSES)[number];

export const COMPANY_SIGN_METHODS = ["auto", "manual", "outside"] as const;
export type CompanySignMethod = (typeof COMPANY_SIGN_METHODS)[number];

export const ESIGN_CONSENT_TEXT = "I agree to sign electronically and that my electronic signature is legally binding.";
export const COMPANY_AUTHORIZATION_TEXT =
  "I authorize 365 Yachts Inc. to apply this signature on my behalf to Broker Agreements and NDAs generated by this platform.";
export const SPLIT_ADDENDUM_WARNING = "Section 1.7: split changes need a signed addendum.";
export const CONTRACT_TIME_ZONE = "America/New_York";
export const MAX_SIGNATURE_PNG_BYTES = 400 * 1024;

export function contractDate(date: Date): string {
  const parts = new Intl.DateTimeFormat("en-US", { timeZone: CONTRACT_TIME_ZONE, year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(date);
  const get = (type: string) => parts.find((part) => part.type === type)?.value ?? "";
  return `${get("month")}/${get("day")}/${get("year")}`;
}

export function easternTimestamp(date: Date): string {
  return new Intl.DateTimeFormat("en-US", {
    timeZone: CONTRACT_TIME_ZONE,
    year: "numeric",
    month: "long",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
    second: "2-digit",
    timeZoneName: "short",
  }).format(date);
}

export function contractStatusLabel(status: ContractStatus | null): string {
  switch (status) {
    case "pending":
      return "Not signed yet";
    case "broker_signed":
      return "Signed by broker · waiting for countersignature";
    case "fully_signed":
      return "Fully signed";
    case "signed_outside":
      return "Signed outside the portal";
    case "voided":
      return "Voided";
    default:
      return "Not started";
  }
}

export function isPngDataUrl(value: string): boolean {
  return /^data:image\/png;base64,[A-Za-z0-9+/]+=*$/.test(value);
}

const textFieldSchema = z.object({
  page: z.number().int().min(1),
  x: z.number(),
  baseline: z.number(),
  size: z.number().positive(),
  maxWidth: z.number().positive().optional(),
  width: z.number().positive().optional(),
  align: z.enum(["left", "center"]).optional(),
  source: z.string().optional(),
});
const imageFieldSchema = z.object({
  page: z.number().int().min(1),
  box: z.tuple([z.number(), z.number(), z.number(), z.number()]),
  kind: z.literal("signature-image"),
  source: z.string().optional(),
});
export const contractFieldMapSchema = z.object({
  template: z.string(),
  description: z.string().optional(),
  units: z.string().optional(),
  font: z.string().optional(),
  fields: z.record(z.string(), z.union([imageFieldSchema, textFieldSchema])),
});
export type ContractFieldMap = z.infer<typeof contractFieldMapSchema>;
export type ContractTextField = z.infer<typeof textFieldSchema>;
export type ContractImageField = z.infer<typeof imageFieldSchema>;

const pngDataUrlSchema = z
  .string()
  .max(Math.ceil((MAX_SIGNATURE_PNG_BYTES * 4) / 3) + 64, "The signature image is too large.")
  .refine(isPngDataUrl, "Send the signature as a PNG image.");

